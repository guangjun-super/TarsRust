//! # Application Module
//!
//! Application lifecycle management for Tars services.

use parking_lot::RwLock;
use std::collections::HashMap;
use std::sync::Arc;
use tokio::signal;
use tokio::sync::watch;
use tokio::task::JoinSet;
use tracing::info;

use crate::communicator::Communicator;
use tars_core::{Result, TarsError};
use tars_protocol::{endpoint::ServantInstance, Endpoint};
use tars_registry::registry::Registrar;
use tars_transport::filter::Filters;
use tars_transport::transport::{ServerProtocolHandler, TarsServer, TarsServerConfig};
use tars_util::{ClientConfig, ServerConfig, TarsConfig};

mod admin;
mod node;

/// Application state
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum AppState {
    /// Not yet started
    Init,
    /// Running
    Running,
    /// Shutting down
    ShuttingDown,
    /// Stopped
    Stopped,
}

type Registration = Option<(Arc<dyn Registrar>, Vec<ServantInstance>)>;

/// Application is the main entry point for Tars services
pub struct Application {
    /// Server configuration
    server_config: RwLock<ServerConfig>,
    /// Client configuration
    client_config: RwLock<ClientConfig>,
    /// Communicator
    communicator: Arc<Communicator>,
    /// Registered servers
    servers: Arc<RwLock<HashMap<String, Arc<TarsServer>>>>,
    /// Object run list
    obj_run_list: RwLock<Vec<String>>,
    /// All filters
    filters: RwLock<Filters>,
    /// Application state
    state: Arc<RwLock<AppState>>,
    registrar: RwLock<Option<Arc<dyn Registrar>>>,
    registration: Arc<tokio::sync::Mutex<Registration>>,
    shutdown_task: parking_lot::Mutex<Option<watch::Receiver<bool>>>,
    /// Shutdown sender
    shutdown_tx: watch::Sender<bool>,
}

impl Default for Application {
    fn default() -> Self {
        Self::new()
    }
}

impl Application {
    /// Create a new Application
    pub fn new() -> Self {
        let (shutdown_tx, _) = watch::channel(false);

        Self {
            server_config: RwLock::new(ServerConfig::default()),
            client_config: RwLock::new(ClientConfig::default()),
            communicator: Arc::new(Communicator::new()),
            servers: Arc::new(RwLock::new(HashMap::new())),
            obj_run_list: RwLock::new(Vec::new()),
            filters: RwLock::new(Filters::new()),
            state: Arc::new(RwLock::new(AppState::Init)),
            shutdown_tx,
            registrar: RwLock::new(None),
            registration: Arc::new(tokio::sync::Mutex::new(None)),
            shutdown_task: parking_lot::Mutex::new(None),
        }
    }

    /// Load the domain/key configuration generated by tarsnode.
    pub fn from_config_file(path: impl AsRef<std::path::Path>) -> Result<Self> {
        let config = TarsConfig::from_file(path)?;
        let mut app = Self::new();
        app.communicator = Arc::new(Communicator::with_config(config.client.clone()));
        app.set_server_config(config.server);
        app.set_client_config(config.client);
        Ok(app)
    }

    /// Parse platform startup arguments (excluding the executable name).
    /// Accepts `--config file`, `--config=file` and the Go-style `-config` forms.
    pub fn from_args<I, S>(args: I) -> Result<Self>
    where
        I: IntoIterator<Item = S>,
        S: AsRef<str>,
    {
        let mut args = args.into_iter();
        let mut path = None;
        while let Some(arg) = args.next() {
            let arg = arg.as_ref();
            let value = if arg == "--config" || arg == "-config" {
                args.next()
                    .map(|s| s.as_ref().to_string())
                    .ok_or_else(|| TarsError::Config("missing --config path".into()))?
            } else if let Some(value) = arg
                .strip_prefix("--config=")
                .or_else(|| arg.strip_prefix("-config="))
            {
                value.to_string()
            } else {
                return Err(TarsError::Config(format!(
                    "unknown startup argument: {arg}"
                )));
            };
            if value.is_empty() || value.starts_with('-') || path.is_some() {
                return Err(TarsError::Config(
                    "--config requires exactly one nonempty path".into(),
                ));
            }
            path = Some(value);
        }
        match path {
            Some(path) => Self::from_config_file(path),
            None => Ok(Self::new()),
        }
    }

    /// Get server configuration
    pub fn server_config(&self) -> ServerConfig {
        self.server_config.read().clone()
    }

    /// Set server configuration
    pub fn set_server_config(&self, config: ServerConfig) {
        self.communicator
            .set_property("enableset", if config.enable_set { "Y" } else { "N" });
        self.communicator
            .set_property("setdivision", &config.set_division);
        *self.server_config.write() = config;
        self.configure_client();
    }

    /// Get client configuration
    pub fn client_config(&self) -> ClientConfig {
        self.client_config.read().clone()
    }

    /// Set client configuration
    pub fn set_client_config(&self, config: ClientConfig) {
        *self.client_config.write() = config;
        self.configure_client();
    }

    fn configure_client(&self) {
        let mut client = self.client_config();
        let server = self.server_config();
        if client.endpoint_cache_path.is_none() && !server.data_path.is_empty() {
            client.endpoint_cache_path = Some(
                std::path::Path::new(&server.data_path)
                    .join(format!("{}.tarsdat", server.server))
                    .to_string_lossy()
                    .into_owned(),
            );
        }
        self.communicator.set_config(client);
    }

    /// Use a custom registrar for business registration and client discovery.
    pub fn set_registrar(&self, registrar: Arc<dyn Registrar>) {
        self.communicator.set_registrar(registrar.clone());
        *self.registrar.write() = Some(registrar);
    }

    async fn registry_callback(
        registrar: &dyn Registrar,
        instance: &ServantInstance,
        register: bool,
    ) {
        let callback = async {
            if register {
                registrar.register(instance).await
            } else {
                registrar.deregister(instance).await
            }
        };
        match tokio::time::timeout(std::time::Duration::from_secs(5), callback).await {
            Ok(Ok(())) => {}
            Ok(Err(error)) => {
                tracing::warn!(servant = %instance.servant, register, "registrar callback failed: {error}")
            }
            Err(_) => {
                tracing::warn!(servant = %instance.servant, register, "registrar callback timed out")
            }
        }
    }

    /// Get communicator
    pub fn communicator(&self) -> Arc<Communicator> {
        Arc::clone(&self.communicator)
    }

    /// Get current state
    pub fn state(&self) -> AppState {
        *self.state.read()
    }

    /// Register a servant at the endpoint configured by the platform.
    pub fn add_servant_from_config<H: ServerProtocolHandler + 'static>(
        &self,
        obj_name: &str,
        handler: H,
    ) -> Result<()> {
        let config = self.server_config();
        let adapters: Vec<_> = config
            .adapters
            .values()
            .filter(|a| a.servant == obj_name)
            .collect();
        if adapters.len() != 1 {
            return Err(TarsError::Config(format!(
                "expected one adapter for {obj_name}, found {}",
                adapters.len()
            )));
        }
        let adapter = adapters[0];
        if adapter.protocol != "tars" {
            return Err(TarsError::Config(format!(
                "unsupported adapter protocol: {}",
                adapter.protocol
            )));
        }
        let address = tcp_address(&adapter.endpoint)?;
        self.add_servant(obj_name, handler, &address)
    }

    /// Add a servant with protocol handler
    pub fn add_servant<H: ServerProtocolHandler + 'static>(
        &self,
        obj_name: &str,
        handler: H,
        address: &str,
    ) -> Result<()> {
        let server_config = self.server_config.read();

        let config = TarsServerConfig::tcp(address)
            .with_max_invoke(server_config.max_invoke)
            .with_accept_timeout(server_config.accept_timeout_duration())
            .with_read_timeout(server_config.read_timeout_duration())
            .with_write_timeout(server_config.write_timeout_duration())
            .with_handle_timeout(server_config.handle_timeout_duration())
            .with_idle_timeout(server_config.idle_timeout_duration())
            .with_queue_cap(server_config.queue_cap)
            .with_tcp_no_delay(server_config.tcp_no_delay);

        let server = TarsServer::new(Arc::new(handler), config);

        let mut servers = self.servers.write();
        if servers.contains_key(obj_name) {
            return Err(TarsError::Config(format!("duplicate servant: {obj_name}")));
        }
        servers.insert(obj_name.to_string(), server);
        self.obj_run_list.write().push(obj_name.to_string());

        info!("Added servant: {} at {}", obj_name, address);
        Ok(())
    }

    /// Run the application
    pub async fn run(&self) -> Result<()> {
        let mut registration = self.registration.lock().await;
        if self.state() != AppState::Init {
            return Err(TarsError::Config("application can only run once".into()));
        }
        info!("Application starting...");
        let config = self.server_config();
        if !config.local.is_empty() {
            self.add_servant(
                "AdminObj",
                admin::Admin {
                    shutdown: self.shutdown_tx.clone(),
                },
                &tcp_address(&config.local)?,
            )?;
        }
        let servers = self.servers.read().clone();
        let node = if config.node.is_empty() {
            None
        } else {
            let mut adapters: Vec<_> = config
                .adapters
                .iter()
                .filter(|(_, adapter)| servers.contains_key(&adapter.servant))
                .map(|(name, _)| name.clone())
                .collect();
            if !config.local.is_empty() {
                adapters.push("AdminAdapter".into());
            }
            Some(node::Node::new(&self.communicator, &config, adapters)?)
        };
        // Bind every socket before reporting readiness. A failure drops all listeners.
        let mut listeners = Vec::new();
        let mut instances = Vec::new();
        for (name, server) in &servers {
            let listener = server.bind().await?;
            if name != "AdminObj" || config.local.is_empty() {
                let address = listener.local_addr()?;
                let adapter = config
                    .adapters
                    .values()
                    .find(|adapter| &adapter.servant == name);
                let mut endpoint = adapter
                    .and_then(|a| tars_protocol::endpoint::parse_endpoint_string(&a.endpoint))
                    .unwrap_or_else(|| Endpoint::tcp(address.ip().to_string(), address.port()));
                endpoint.port = address.port();
                instances.push(ServantInstance {
                    tars_version: env!("CARGO_PKG_VERSION").into(),
                    app: config.app.clone(),
                    server: config.server.clone(),
                    enable_set: config.enable_set,
                    set_division: config.set_division.clone(),
                    servant: name.clone(),
                    protocol: adapter.map_or("tars", |a| a.protocol.as_str()).into(),
                    endpoint,
                });
            }
            info!("Starting server: {name}");
            listeners.push((server.clone(), listener));
        }
        let mut handles = JoinSet::new();
        for (server, listener) in listeners {
            handles.spawn(server.serve_with_listener(listener));
        }
        *self.state.write() = AppState::Running;
        let mut reporters = JoinSet::new();
        if let Some(node) = node {
            reporters.spawn(node.run(self.shutdown_tx.subscribe()));
        }
        let registrar = self.registrar.read().clone();
        if let Some(registrar) = registrar {
            *registration = Some((registrar.clone(), instances.clone()));
            for instance in &instances {
                Self::registry_callback(registrar.as_ref(), instance, true).await;
            }
        }
        drop(registration);
        let mut result = Ok(());
        tokio::select! {
            _ = self.wait_for_shutdown() => {},
            stopped = handles.join_next(), if !handles.is_empty() => {
                result = match stopped {
                    Some(Ok(Err(error))) => Err(error),
                    Some(Err(error)) => Err(TarsError::Protocol(format!("server task failed: {error}"))),
                    _ => Err(TarsError::Protocol("server stopped unexpectedly".into())),
                };
            },
        }
        self.shutdown_tx.send_replace(true);
        while reporters.join_next().await.is_some() {}
        self.shutdown().await?;
        while let Some(stopped) = handles.join_next().await {
            if let Ok(Err(error)) = stopped {
                result = Err(error);
            }
        }
        *self.state.write() = AppState::Stopped;
        info!("Application stopped");
        result
    }

    /// Wait for shutdown signal
    async fn wait_for_shutdown(&self) {
        let mut shutdown_rx = self.shutdown_tx.subscribe();
        if *shutdown_rx.borrow() {
            return;
        }
        #[cfg(unix)]
        let mut terminate = signal::unix::signal(signal::unix::SignalKind::terminate())
            .expect("failed to install SIGTERM handler");
        tokio::select! {
            _ = signal::ctrl_c() => {
                info!("Received Ctrl+C, shutting down...");
            }
            _ = shutdown_rx.changed() => {
                info!("Received shutdown signal");
            }
            _ = async {
                #[cfg(unix)]
                terminate.recv().await;
                #[cfg(not(unix))]
                std::future::pending::<()>().await;
            } => { info!("Received termination signal"); }
        }
    }

    /// Shutdown the application gracefully
    pub async fn shutdown(&self) -> Result<()> {
        // Own cleanup independently of any individual caller's future.
        self.shutdown_tx.send_replace(true);
        let mut completion = {
            let mut task = self.shutdown_task.lock();
            task.get_or_insert_with(|| {
                let (done, completion) = watch::channel(false);
                let registration = self.registration.clone();
                let servers = self.servers.clone();
                let state = self.state.clone();
                tokio::spawn(async move {
                    let mut registration = registration.lock().await;
                    *state.write() = AppState::ShuttingDown;
                    if let Some((registrar, instances)) = registration.take() {
                        for instance in &instances {
                            Self::registry_callback(registrar.as_ref(), instance, false).await;
                        }
                    }
                    drop(registration);
                    let servers = servers.read().clone();
                    let mut shutdowns = JoinSet::new();
                    for (_, server) in servers {
                        shutdowns.spawn(async move { server.shutdown().await });
                    }
                    while shutdowns.join_next().await.is_some() {}
                    *state.write() = AppState::Stopped;
                    done.send_replace(true);
                });
                completion
            })
            .clone()
        };
        while !*completion.borrow_and_update() {
            completion
                .changed()
                .await
                .map_err(|_| TarsError::Protocol("shutdown task stopped unexpectedly".into()))?;
        }
        Ok(())
    }

    /// Send shutdown signal
    pub fn signal_shutdown(&self) {
        self.shutdown_tx.send_replace(true);
    }

    /// Register client filter middleware
    pub fn use_client_filter_middleware(
        &self,
        middleware: tars_transport::filter::ClientFilterMiddleware,
    ) {
        self.filters.write().use_client_middleware(middleware);
    }

    /// Register server filter middleware
    pub fn use_server_filter_middleware(
        &self,
        middleware: tars_transport::filter::ServerFilterMiddleware,
    ) {
        self.filters.write().use_server_middleware(middleware);
    }
}

fn tcp_address(endpoint: &str) -> Result<String> {
    let parsed = Endpoint::from_string(endpoint)
        .ok_or_else(|| TarsError::Config(format!("invalid endpoint: {endpoint}")))?;
    if !parsed.is_tcp() {
        return Err(TarsError::Config(format!(
            "platform listeners currently require TCP: {endpoint}"
        )));
    }
    let parts: Vec<_> = endpoint.split_whitespace().collect();
    let host = parts
        .windows(2)
        .find(|pair| pair[0] == "-b")
        .map(|pair| pair[1])
        .unwrap_or(&parsed.host);
    Ok(if host.contains(':') {
        format!("[{host}]:{}", parsed.port)
    } else {
        format!("{host}:{}", parsed.port)
    })
}

/// Builder for Application
pub struct ApplicationBuilder {
    app: Application,
}

impl Default for ApplicationBuilder {
    fn default() -> Self {
        Self::new()
    }
}

impl ApplicationBuilder {
    pub fn new() -> Self {
        Self {
            app: Application::new(),
        }
    }

    pub fn server_config(self, config: ServerConfig) -> Self {
        self.app.set_server_config(config);
        self
    }

    pub fn client_config(self, config: ClientConfig) -> Self {
        self.app.set_client_config(config);
        self
    }

    pub fn build(self) -> Application {
        self.app
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_application_creation() {
        let app = Application::new();
        assert_eq!(app.state(), AppState::Init);
    }

    #[test]
    fn test_application_builder() {
        let config = ServerConfig {
            app: "Test".to_string(),
            server: "HelloServer".to_string(),
            ..Default::default()
        };

        let app = ApplicationBuilder::new().server_config(config).build();

        assert_eq!(app.server_config().app, "Test");
        assert_eq!(app.server_config().server, "HelloServer");
    }

    #[test]
    fn test_application_communicator() {
        let app = Application::new();
        let comm = app.communicator();
        assert!(comm.locator().is_empty());
    }
}
